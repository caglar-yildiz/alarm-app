#!/usr/bin/env python3
"""Converts the Android strings.xml files into iOS Localizable.strings / .stringsdict files.

Run from the repository root: python3 ios/tools/convert_strings.py
Android stays the source of truth; iOS-only texts and overrides live in ios/tools/ios_strings.json.
"""
import json, os, re, xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RES = os.path.join(ROOT, "app", "src", "main", "res")
OUT = os.path.join(ROOT, "ios", "BENG", "Resources", "Localization")
LANGS = {"values": "en", "values-tr": "tr", "values-de": "de", "values-fr": "fr", "values-es": "es",
         "values-it": "it", "values-pt-rBR": "pt-BR", "values-nl": "nl", "values-ja": "ja", "values-ko": "ko",
         "values-zh-rTW": "zh-Hant", "values-ar": "ar", "values-th": "th", "values-in": "id"}

def text(node):
    value = "".join(node.itertext())
    value = re.sub(r"\\n", "\n", value)
    value = value.replace("\\'", "'").replace('\\"', '"').replace("\\@", "@").replace("\\?", "?")
    if len(value) >= 2 and value[0] == '"' and value[-1] == '"':
        value = value[1:-1]
    # Android printf -> Cocoa: strings become objects, ints become longs (Swift Int is 64-bit).
    value = re.sub(r"%(\d+\$)?s", lambda m: "%" + (m.group(1) or "") + "@", value)
    value = re.sub(r"%(\d+\$)?d", lambda m: "%" + (m.group(1) or "") + "ld", value)
    return value

def quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

extra = json.load(open(os.path.join(ROOT, "ios", "tools", "ios_strings.json"), encoding="utf-8"))

for folder, lang in LANGS.items():
    root = ET.parse(os.path.join(RES, folder, "strings.xml")).getroot()
    strings, plurals = {}, {}
    for node in root:
        name = node.get("name")
        if node.tag == "string":
            strings[name] = text(node)
        elif node.tag == "string-array":
            items = [text(item) for item in node.findall("item")]
            for index, item in enumerate(items):
                strings[f"{name}_{index}"] = item
            strings[f"{name}_count"] = str(len(items))
        elif node.tag == "plurals":
            plurals[name] = {item.get("quantity"): text(item) for item in node.findall("item")}
    for key, values in extra.items():
        if lang in values:
            strings[key] = values[lang]
    target = os.path.join(OUT, f"{lang}.lproj")
    os.makedirs(target, exist_ok=True)
    with open(os.path.join(target, "Localizable.strings"), "w", encoding="utf-8") as out:
        out.write("/* Generated by ios/tools/convert_strings.py from Android strings.xml. Do not edit. */\n")
        for key in sorted(strings):
            out.write(f"{quote(key)} = {quote(strings[key])};\n")
    with open(os.path.join(target, "Localizable.stringsdict"), "w", encoding="utf-8") as out:
        out.write('<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
                  '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n')
        for key in sorted(plurals):
            out.write(f"\t<key>{escape(key)}</key>\n\t<dict>\n\t\t<key>NSStringLocalizedFormatKey</key>\n"
                      f"\t\t<string>%#@value@</string>\n\t\t<key>value</key>\n\t\t<dict>\n"
                      f"\t\t\t<key>NSStringFormatSpecTypeKey</key>\n\t\t\t<string>NSStringPluralRuleType</string>\n"
                      f"\t\t\t<key>NSStringFormatValueTypeKey</key>\n\t\t\t<string>ld</string>\n")
            forms = plurals[key]
            if "other" not in forms:
                forms["other"] = list(forms.values())[-1]
            for quantity, value in forms.items():
                out.write(f"\t\t\t<key>{quantity}</key>\n\t\t\t<string>{escape(value)}</string>\n")
            out.write("\t\t</dict>\n\t</dict>\n")
        out.write("</dict>\n</plist>\n")
    print(lang, len(strings), "strings,", len(plurals), "plurals")
